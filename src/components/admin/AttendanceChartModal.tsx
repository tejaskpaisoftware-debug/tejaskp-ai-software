"use client";

import { useState, useEffect } from "react";
import { motion, AnimatePresence } from "framer-motion";
import { Calendar, BarChart3, FileText, Send, X, ArrowLeft, Sparkles, CheckCircle2, Clock, AlertCircle } from "lucide-react";

interface AttendanceRecord {
    id?: string;
    date: string;
    status: string;
    isSunday: boolean;
    loginTime?: string;
    logoutTime?: string;
}

interface AttendanceChartModalProps {
    isOpen: boolean;
    onClose: () => void;
    userId: string;
    userName: string;
}

export default function AttendanceChartModal({ isOpen, onClose, userId, userName }: AttendanceChartModalProps) {
    const [chartData, setChartData] = useState<AttendanceRecord[]>([]);
    const [view, setView] = useState<'CHART' | 'REPORT'>('CHART');
    const [insight, setInsight] = useState<string>("");
    const [stats, setStats] = useState<any>(null);
    const [loading, setLoading] = useState(true);
    const [insightLoading, setInsightLoading] = useState(true);
    const [isSharing, setIsSharing] = useState(false);
    const [shareResult, setShareResult] = useState<{ success: boolean; msg: string } | null>(null);

    useEffect(() => {
        if (isOpen && userId) {
            setView('CHART');
            fetchChartData();
        } else {
            setChartData([]);
            setInsight("");
            setStats(null);
            setShareResult(null);
        }
    }, [isOpen, userId]);

    useEffect(() => {
        if (chartData.length > 0) {
            const newStats = {
                present: chartData.filter(d => d.status === 'PRESENT').length,
                late: chartData.filter(d => d.status === 'LATE').length,
                absent: chartData.filter(d => d.status === 'ABSENT').length,
                off: chartData.filter(d => d.status === 'OFF').length
            };
            setStats(newStats);
        }
    }, [chartData]);

    const fetchChartData = async () => {
        setLoading(true);
        setInsightLoading(true);
        try {
            const res = await fetch(`/api/admin/users/${userId}/attendance-chart`);
            if (res.ok) {
                const data = await res.json();
                setChartData(data.chartData);
                fetchInsight(data.chartData);
            }
        } catch (error) {
            console.error("Failed to fetch chart", error);
        } finally {
            setLoading(false);
        }
    };

    const fetchInsight = async (data: AttendanceRecord[]) => {
        try {
            const res = await fetch(`/api/admin/users/${userId}/attendance-insights`, {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({ chartData: data })
            });
            if (res.ok) {
                const result = await res.json();
                setInsight(result.insight || result.fallbackInsight);
                setStats(result.stats);
            }
        } catch (error) {
            console.error("Failed to fetch AI insight", error);
            setInsight("AI is currently unavailable to analyze patterns.");
        } finally {
            setInsightLoading(false);
        }
    };

    const handleToggleStatus = async (date: string, currentStatus: string) => {
        const statusMap: Record<string, string> = {
            'PRESENT': 'LATE',
            'LATE': 'ABSENT',
            'ABSENT': 'OFF',
            'OFF': 'PRESENT',
            'NOT_JOINED': 'PRESENT',
            'WEEKEND': 'PRESENT'
        };

        const newStatus = statusMap[currentStatus] || 'PRESENT';

        setChartData(prev => prev.map(item =>
            item.date === date ? { ...item, status: newStatus } : item
        ));

        try {
            await fetch(`/api/admin/users/${userId}/attendance-toggle`, {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({ date, status: newStatus })
            });
        } catch (err) {
            console.error("Status update error", err);
        }
    };

    const handleShare = async () => {
        setIsSharing(true);
        setShareResult(null);

        const finalStats = stats || {
            present: chartData.filter(d => d.status === 'PRESENT').length,
            late: chartData.filter(d => d.status === 'LATE').length,
            absent: chartData.filter(d => d.status === 'ABSENT').length,
            off: chartData.filter(d => d.status === 'OFF').length
        };

        const finalInsight = insight || "Attendance report generated by system administrator.";

        try {
            const res = await fetch(`/api/admin/users/${userId}/attendance-share`, {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({ stats: finalStats, insight: finalInsight })
            });
            const data = await res.json();
            if (data.success) {
                setShareResult({ success: true, msg: "Successfully delivered via WhatsApp!" });
            } else {
                setShareResult({ success: false, msg: data.error || "Failed to deliver message." });
            }
        } catch (error) {
            setShareResult({ success: false, msg: "Network error during share." });
        } finally {
            setIsSharing(false);
        }
    };

    return (
        <AnimatePresence>
            {isOpen && (
                <motion.div
                    initial={{ opacity: 0 }}
                    animate={{ opacity: 1 }}
                    exit={{ opacity: 0 }}
                    className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-sm"
                >
                    <motion.div
                        initial={{ scale: 0.95, y: 15 }}
                        animate={{ scale: 1, y: 0 }}
                        className="bg-white border border-slate-200 rounded-2xl w-full max-w-2xl overflow-hidden shadow-2xl relative flex flex-col max-h-[85vh]"
                    >
                        {/* Header */}
                        <div className="p-6 border-b border-slate-100 flex justify-between items-center bg-slate-50/70">
                            <div className="flex items-center gap-3">
                                {view === 'REPORT' && (
                                    <button
                                        onClick={() => setView('CHART')}
                                        className="p-1.5 hover:bg-slate-200 rounded-lg text-slate-600 transition-colors"
                                    >
                                        <ArrowLeft size={16} />
                                    </button>
                                )}
                                <div>
                                    <h2 className="text-lg font-bold text-slate-900 flex items-center gap-2">
                                        {view === 'CHART' ? <BarChart3 className="w-5 h-5 text-amber-600" /> : <FileText className="w-5 h-5 text-amber-600" />}
                                        {view === 'CHART' ? 'Attendance Heatmap' : 'Detailed Attendance Ledger'}
                                    </h2>
                                    <p className="text-xs text-slate-500 mt-0.5">30-day activity logs for <strong className="text-amber-700 font-semibold">{userName}</strong></p>
                                </div>
                            </div>
                            <button 
                                onClick={onClose} 
                                className="w-8 h-8 rounded-lg flex items-center justify-center text-slate-400 hover:text-slate-700 hover:bg-slate-200 transition-colors"
                            >
                                <X size={18} />
                            </button>
                        </div>

                        {/* Content */}
                        <div className="p-6 space-y-5 overflow-y-auto flex-1">
                            {loading ? (
                                <div className="py-20 text-center animate-pulse text-slate-400 font-medium text-xs uppercase tracking-wider">
                                    Aggregating Attendance Records...
                                </div>
                            ) : (
                                <>
                                    {view === 'CHART' ? (
                                        <>
                                            {/* Legend */}
                                            <div className="flex flex-wrap gap-4 text-xs font-bold text-slate-600 justify-center">
                                                <div className="flex items-center gap-1.5"><span className="w-2.5 h-2.5 rounded-full bg-emerald-500"></span> Present</div>
                                                <div className="flex items-center gap-1.5"><span className="w-2.5 h-2.5 rounded-full bg-amber-500"></span> Late</div>
                                                <div className="flex items-center gap-1.5"><span className="w-2.5 h-2.5 rounded-full bg-rose-500"></span> Absent</div>
                                                <div className="flex items-center gap-1.5"><span className="w-2.5 h-2.5 rounded-full bg-slate-300"></span> Off / Weekend</div>
                                            </div>

                                            {/* Grid */}
                                            <div className="grid grid-cols-7 gap-2 bg-slate-50 p-4 rounded-2xl border border-slate-200">
                                                {chartData.map((day, idx) => {
                                                    let bg = "bg-white border-slate-200 text-slate-400";
                                                    let title = "Not Joined / Weekend";

                                                    if (day.status === "PRESENT") { bg = "bg-emerald-50 border-emerald-300 text-emerald-700 font-bold"; title = "Present"; }
                                                    else if (day.status === "LATE") { bg = "bg-amber-50 border-amber-300 text-amber-700 font-bold"; title = "Late"; }
                                                    else if (day.status === "ABSENT") { bg = "bg-rose-50 border-rose-300 text-rose-700 font-bold"; title = "Absent"; }
                                                    else if (day.status === "OFF") { bg = "bg-slate-100 border-slate-300 text-slate-500"; title = "Off Day"; }

                                                    const d = new Date(day.date);
                                                    const dateNum = d.getDate();
                                                    const monthNames = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
                                                    const monthName = monthNames[d.getMonth()];

                                                    return (
                                                        <div
                                                            key={idx}
                                                            title={`${day.date} - ${title} (Click to toggle)`}
                                                            onClick={() => handleToggleStatus(day.date, day.status)}
                                                            className={`aspect-square rounded-xl shadow-2xs border flex flex-col items-center justify-center transition-all hover:scale-105 active:scale-95 cursor-pointer select-none ${bg}`}
                                                        >
                                                            <span className="text-[9px] opacity-60 uppercase font-semibold leading-none">{monthName}</span>
                                                            <span className="text-xs font-extrabold mt-0.5">{dateNum}</span>
                                                        </div>
                                                    );
                                                })}
                                            </div>
                                            <p className="text-[11px] text-center text-slate-400">💡 Click any date box to cycle its attendance status.</p>
                                        </>
                                    ) : (
                                        <div className="space-y-2">
                                            {chartData.slice().reverse().map((day, idx) => {
                                                if (day.status === 'NOT_JOINED' || day.status === 'WEEKEND') return null;

                                                const formatTime = (time?: string) => {
                                                    if (!time) return '--:--';
                                                    return new Date(time).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
                                                };

                                                return (
                                                    <div key={idx} className="bg-slate-50 border border-slate-200 p-3 rounded-xl flex justify-between items-center hover:bg-slate-100/70 transition-colors">
                                                        <div className="flex items-center gap-3">
                                                            <div className={`w-1.5 h-7 rounded-full ${
                                                                day.status === 'PRESENT' ? 'bg-emerald-500' :
                                                                day.status === 'LATE' ? 'bg-amber-500' :
                                                                day.status === 'ABSENT' ? 'bg-rose-500' : 'bg-slate-300'
                                                            }`} />
                                                            <div>
                                                                <div className="font-semibold text-xs text-slate-900">
                                                                    {new Date(day.date).toLocaleDateString(undefined, { weekday: 'short', month: 'short', day: 'numeric' })}
                                                                </div>
                                                                <div className="text-[10px] text-slate-400 uppercase font-bold tracking-wider">{day.status}</div>
                                                            </div>
                                                        </div>
                                                        <div className="flex gap-6 text-right">
                                                            <div>
                                                                <div className="text-[10px] text-slate-400 uppercase">Login</div>
                                                                <div className="text-xs font-mono text-slate-700 font-semibold">{formatTime(day.loginTime)}</div>
                                                            </div>
                                                            <div>
                                                                <div className="text-[10px] text-slate-400 uppercase">Logout</div>
                                                                <div className="text-xs font-mono text-slate-700 font-semibold">{formatTime(day.logoutTime)}</div>
                                                            </div>
                                                        </div>
                                                    </div>
                                                );
                                            })}
                                        </div>
                                    )}

                                    {/* AI Insights Section */}
                                    <div className="bg-gradient-to-br from-amber-50/50 via-white to-amber-50/30 border border-amber-200 rounded-2xl p-5 relative overflow-hidden">
                                        <div className="flex items-center gap-2 text-amber-800 font-bold mb-2 text-xs tracking-wider uppercase">
                                            <Sparkles className="w-4 h-4 text-amber-600" /> Automated Performance Insight
                                        </div>

                                        {insightLoading ? (
                                            <div className="animate-pulse text-slate-400 text-xs">Analyzing punctuality patterns...</div>
                                        ) : (
                                            <div className="text-slate-700 text-xs leading-relaxed">
                                                {insight}
                                            </div>
                                        )}

                                        {stats && !insightLoading && (
                                            <div className="mt-3 pt-3 border-t border-amber-200/60 flex gap-5 text-xs font-bold">
                                                <div><span className="text-slate-400">Present:</span> <span className="text-emerald-600">{stats.present}</span></div>
                                                <div><span className="text-slate-400">Late:</span> <span className="text-amber-600">{stats.late}</span></div>
                                                <div><span className="text-slate-400">Absent:</span> <span className="text-rose-600">{stats.absent}</span></div>
                                                <div><span className="text-slate-400">Off:</span> <span className="text-slate-600">{stats.off || 0}</span></div>
                                            </div>
                                        )}
                                    </div>

                                    {shareResult && (
                                        <div className={`text-center text-xs font-semibold p-2.5 rounded-xl ${
                                            shareResult.success ? 'text-emerald-800 bg-emerald-50 border border-emerald-200' : 'text-rose-800 bg-rose-50 border border-rose-200'
                                        }`}>
                                            {shareResult.msg}
                                        </div>
                                    )}

                                    <div className="flex gap-3 pt-1">
                                        <button
                                            onClick={() => setView(view === 'CHART' ? 'REPORT' : 'CHART')}
                                            className="flex-1 py-3 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-800 font-bold text-xs uppercase tracking-wider flex items-center justify-center gap-2 transition-colors"
                                        >
                                            {view === 'CHART' ? 'Detailed Ledger' : 'Back to Heatmap'}
                                        </button>
                                        <button
                                            onClick={handleShare}
                                            disabled={insightLoading || isSharing}
                                            className="flex-1 py-3 rounded-xl bg-emerald-600 hover:bg-emerald-700 text-white font-bold text-xs uppercase tracking-wider flex items-center justify-center gap-2 transition-colors shadow-sm disabled:opacity-50"
                                        >
                                            <Send className="w-3.5 h-3.5" />
                                            {isSharing ? "Dispatching..." : "Share via WhatsApp"}
                                        </button>
                                    </div>
                                </>
                            )}
                        </div>
                    </motion.div>
                </motion.div>
            )}
        </AnimatePresence>
    );
}
